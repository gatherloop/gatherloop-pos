CREATE TABLE IF NOT EXISTS `payments` (
    `id`                   BIGINT      NOT NULL AUTO_INCREMENT,
    `cart_id`              BIGINT      NOT NULL,
    `session_id`           CHAR(36)    NOT NULL,
    `transaction_id`       BIGINT      NULL,
    `partner_reference_no` VARCHAR(64) NOT NULL,
    `gateway_reference_no` VARCHAR(64) NOT NULL DEFAULT '',
    `method`               VARCHAR(16) NOT NULL DEFAULT 'qris',
    `status`               VARCHAR(16) NOT NULL DEFAULT 'pending',
    `amount`               FLOAT       NOT NULL DEFAULT 0,
    `qr_content`           TEXT        NULL,
    `expired_at`           DATETIME    NOT NULL,
    `paid_at`              DATETIME    NULL,
    `status_checked_at`    DATETIME    NULL,
    `created_at`           DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at`           DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted_at`           DATETIME    NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uq_payments_partner_reference_no` (`partner_reference_no`),
    KEY `idx_payments_cart_id_status` (`cart_id`, `status`),
    KEY `idx_payments_session_id` (`session_id`),
    CONSTRAINT `fk_payments_cart`        FOREIGN KEY (`cart_id`)        REFERENCES `carts`        (`id`),
    CONSTRAINT `fk_payments_transaction` FOREIGN KEY (`transaction_id`) REFERENCES `transactions` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
